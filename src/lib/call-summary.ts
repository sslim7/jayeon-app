/**
 * 요약 한 덩어리를 **읽을 수 있는 줄들로** 끊는다.
 *
 * ┌──────────────────────────────────────────────────────────────────────────────┐
 * │ 🔴 **모델은 요약을 한 문단으로 준다.** 서버가 받는 것도 문자열 하나다              │
 * │ (§`jayeon-was/internal/calls/model.go` 의 `summary`).                          │
 * └──────────────────────────────────────────────────────────────────────────────┘
 * 실제 요약은 서너 문장이 이어 붙은 300자쯤인데, 그대로 한 덩어리로 그리면 **어디까지가 한
 * 이야기인지 눈으로 잡히지 않는다** — 보고서를 여는 이유가 「이 통화가 뭐였지」를 3초 안에
 * 아는 것이라 그 한 덩어리가 곧 이 화면의 실패다. 문장마다 줄을 나누면 훑는 눈이 문장 앞에
 * 설 자리를 얻는다.
 *
 * 🔴 **줄을 나누는 일은 화면이 아니라 여기서 한다.** 아래 규칙은 눈으로 검사하기 어렵고
 * (「1.5개월」이 두 줄로 갈라지는 것은 그 요약을 가진 통화를 열어 봐야 보인다), 컴포넌트
 * 안에 있으면 검사할 방법이 화면을 띄우는 것뿐이다. 여기 있으면 `tests/call-summary.test.cjs`
 * 가 문장 하나 단위로 잡는다.
 */

/**
 * 문장 끝으로 **칠 수 있는** 문장부호. 한국어 요약은 거의 전부 마침표로 끝나지만, 모델이
 * 물음표·느낌표를 섞어 쓰는 경우가 있어 함께 본다. `…` 은 말줄임표 한 글자 형태다.
 */
const ENDINGS = '.!?…';

/**
 * 조각 하나가 문장으로 설 수 있는 최소 길이.
 *
 * ⚠️ 이 하한이 없으면 「1. 이상형 확인」 같은 **번호 매김이 그 자리에서 갈라진다** — 「1.」만
 * 남은 줄과 내용만 남은 줄이 따로 서고, 원래 문장은 어디에도 없다.
 */
const MIN_SENTENCE = 6;

/**
 * 한국어 **서술 종결어미의 마지막 글자.**
 *
 * ┌──────────────────────────────────────────────────────────────────────────────┐
 * │ ⚠️ **마침표만으로는 문장 끝인지 알 수 없다.** 「파티와 기간제 등. 여러 방식을…」의   │
 * │ 「등.」은 문장 끝이 아니라 열거의 꼬리다.                                        │
 * └──────────────────────────────────────────────────────────────────────────────┘
 * 그래서 마침표 **앞 글자**까지 본다. 분석 요약은 전부 서술체(「…안내했다.」·「…마무리했다.」)
 * 라 이 집합으로 끊을 자리가 잡히고, 여기 없는 글자로 끝나면 **끊지 않는다.**
 *
 * 🔴 **못 끊는 쪽이 안전한 실패다.** 못 끊으면 지금까지처럼 한 문단으로 보일 뿐이지만,
 * 잘못 끊으면 없던 문장이 생겨 **요약이 하지 않은 말을 한 것처럼 보인다.** 그래서 애매하면
 * 끊지 않는 쪽으로 판정한다. 영문 문장(`... done.`)은 라틴 문자로 따로 받는다.
 */
const ENDING_SYLLABLES = '다요죠음함임됨네까오지라군야밌셨';

/** 마침표 앞에 붙는 닫는 따옴표·괄호. 「…라고 했다".」처럼 인용이 끝나는 자리다. */
const CLOSERS = /["'”’」』)）\]］》〉]+$/;

/** 이 마침표가 **문장을 닫는가.** 위 `ENDING_SYLLABLES` 의 판정을 실제로 수행한다. */
function closesSentence(buffer: string): boolean {
  const body = buffer.replace(/[.!?…]+$/, '').replace(CLOSERS, '');
  const last = body[body.length - 1];
  if (!last) return false;
  return ENDING_SYLLABLES.includes(last) || /[A-Za-z]/.test(last);
}

/**
 * 요약 문자열을 문장 단위로 끊는다. 끊을 자리가 없으면 **원문 한 줄을 그대로 돌려준다** —
 * 빈 배열을 돌려주면 부르는 쪽이 요약이 없는 것과 구별하지 못해 화면에서 요약이 사라진다.
 *
 * 규칙 넷(전부 「잘못 끊기지 않게」가 목적이다):
 * 1. 숫자에 끼인 점은 문장부호가 아니다 — 「1.5개월」·「3.4대1」.
 * 2. 뒤에 공백이 없으면 아직 문장이 끝나지 않았다 — 「www.themay.co.kr」·「A.I.」.
 * 3. 너무 짧게 끝난 조각은 번호 매김이다(→ 위 `MIN_SENTENCE`).
 * 4. 마침표 앞이 서술 종결어미가 아니면 열거의 꼬리다(→ 위 `ENDING_SYLLABLES`).
 *
 * ⚠️ 문장부호를 **버리지 않는다.** 마침표를 떼면 남은 줄이 제목처럼 읽혀, 문장 셋이 항목
 * 셋으로 보인다 — 요약은 목록이 아니라 문단이다.
 */
export function summaryLines(summary: string): string[] {
  const text = summary.trim();
  if (!text) return [];
  const lines: string[] = [];
  let buffer = '';
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    buffer += char;
    if (!ENDINGS.includes(char)) continue;
    const before = text[i - 1];
    const after = text[i + 1];
    // ① 숫자 사이의 점.
    if (before && after && /\d/.test(before) && /\d/.test(after)) continue;
    // ② 문장부호 뒤가 공백도 문서 끝도 아니면 낱말 안이다.
    if (after && !/\s/.test(after)) continue;
    // ③ 번호 매김.
    if (buffer.trim().length < MIN_SENTENCE) continue;
    // ④ 마침표만 특별히 더 본다 — 물음표·느낌표는 열거의 꼬리로 쓰이지 않는다.
    if (char === '.' && !closesSentence(buffer)) continue;
    lines.push(buffer.trim());
    buffer = '';
  }
  // 마침표 없이 끝나는 요약이 실제로 온다. 남은 꼬리를 버리면 마지막 문장이 사라진다.
  if (buffer.trim()) lines.push(buffer.trim());
  return lines;
}
